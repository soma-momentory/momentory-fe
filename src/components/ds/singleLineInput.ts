import { type TextStyle } from "react-native";

/**
 * **한 줄 입력의 세로 정렬** — 검색칸 · 일정 입력 · `TextField` 가 나눠 쓴다.
 *
 * 한 줄 `TextInput` 을 그냥 두면 두 가지가 함께 어긋난다. 하나만 고치면 다른 하나가
 * 드러나서 두 번 밟았다(2026-08-28 · 17 Pro Max · 스크린샷 픽셀 실측):
 *
 * 1. **받침이 잘린다.** 바깥 줄의 `alignItems: "center"` 는 입력칸을 **글꼴의 자연 줄
 *    높이**로 만드는데, 그 상자가 한글 글자보다 낮다 — 잉크가 40px 여야 할 자리에서
 *    34px 로 깎였다. `alignSelf: "stretch"` 로 상자를 칸 높이만큼 늘여 자리를 준다.
 * 2. ~~늘이면 글자가 아래로 쏠린다~~ — **2026-09-13 에 없앴다.** 아래 절을 본다.
 *
 * **안드로이드에는 보정을 넣지 않는다** — 거기는 `textAlignVertical: "center"` 가 상자
 * 안에서 글자를 가운데 놓아 쏠림이 없다(iOS 는 이 속성을 무시한다).
 *
 * ## iOS 위로 당기던 여백을 걷어냈다 (2026-09-13 · 실기기 스크린샷)
 *
 * 예전에는 iOS 에만 `marginBottom = fontSize × (4/15) × 2` 를 줘서 글자를 위로 당겼다.
 * **Pretendard 15pt 에서 4pt 내려앉던 것**을 되돌리려고 2026-08-28 에 눈으로 잰 값이다.
 *
 * 그 뒤 **서체가 교보손글씨로 바뀌었다**(2026-09-06). 이 손글씨는 Pretendard 와 **반대로
 * 글자칸 위쪽에 붙는다** — 같은 사실을 홈 날짜가 `HAND_TOP_BEARING`(0.1)으로 적어 두고
 * 있다. 그래서 이 여백은 **이미 위로 뜬 글자를 더 위로 밀고** 있었고, 크기에 비례하는
 * 값이라 §2 의 iOS 타입 보정(1.2)이 들어가면서 8.5 → 10.1pt 로 커져 눈에 띄었다
 * (온보딩 닉네임 pill 의 플레이스홀더·커서가 함께 떠 보였다).
 *
 * **상수를 다시 재지 않고 뺐다.** 눈으로 잰 값은 잰 조건(서체·크기)이 바뀌면 또 틀어진다 —
 * 이번이 그 두 번째다. 지금은 `alignSelf: "stretch"` 로 받침 자리만 주고 세로 위치는
 * 손대지 않는다.
 *
 * ⚠ 되살려야 할 일이 생기면 **서체마다 값이 다르다**는 것부터 본다. 로그인(`S1`)만
 * Pretendard 인데 거기에는 한 줄 입력이 없다.
 *
 * ⚠ **줄 간격(`lineHeight`)으로 풀려고 하지 말 것** — iOS 는 한 줄 입력에 줄 간격이
 * 있으면 글자를 줄 상자 **바닥에** 붙여 그린다. 여러 줄 입력에서만 뜻이 있다.
 */
export const singleLineInput = (): TextStyle => ({
  alignSelf: "stretch",
  textAlignVertical: "center",
});
