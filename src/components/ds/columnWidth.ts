import { PixelRatio } from "react-native";

/**
 * 열 수가 **고정된** 격자의 칸 폭 — 감정 선택 3열(`ChoiceGrid`)과 달력 7열
 * (`Calendar`)이 나눠 쓴다.
 *
 * ## 왜 퍼센트로 두지 않나
 *
 * `width: '14.2857%'` 처럼 나누면 Yoga 가 칸마다 기기 픽셀로 **반올림**하는데,
 * 일곱 칸이 각자 조금씩 올라가면 합이 부모 폭을 넘는다. `flexWrap` 이 걸린
 * 격자에서는 그 순간 **마지막 칸이 다음 줄로 넘어간다** — 좁은 기기에서 한 주가
 * 6+1 로 접히고 감정 9칸의 3×3 이 깨지던 자리다. `gap` 이 붙으면 (감정 격자가
 * 그렇다) 간격까지 퍼센트 밖에서 더해져 더 쉽게 넘친다.
 *
 * 그래서 **실제 폭을 재고**(`onLayout`) 간격을 먼저 뺀 뒤, 기기 픽셀 격자 아래로
 * **내림**한다. 합이 부모를 넘지 않는 것이 보장되므로 줄이 밀리지 않는다.
 * 내림하고 남는 1px 남짓은 격자를 가운데 정렬해 양옆으로 흘린다.
 *
 * ## 왜 **한 픽셀을 더 빼나**
 *
 * 내림만으로는 모자랐다. 3배 밀도 기기에서 남은 폭이 3의 배수면 내림이 아무것도
 * 깎지 않아 `칸×열 + 간격 = 부모` 로 **딱 맞는다**. 그런데 JS 의 배정밀도 값이
 * Yoga 로 넘어갈 때 **32비트 float 으로 좁혀지면서** 위로 반올림되는 폭이 있다 —
 * 그 순간 합이 부모를 1e-5pt 넘고 `flexWrap` 이 마지막 칸을 다음 줄로 민다.
 *
 * | 부모 | 남은 폭 | 칸(double) | 칸(float32) | ×3 |
 * | --- | --- | --- | --- | --- |
 * | 393(16) | 329 | 109.666666… | 109.666664 | 328.99 ✅ |
 * | 428(13PM) | 364 | 121.333333… | 121.333336 | **364.0000076 ❌** |
 * | 440(17PM) | 376 | 125.333333… | 125.333336 | **376.0000076 ❌** |
 *
 * 실제로 2026-08-28 에 **13 Pro Max·17 Pro Max 에서만** 감정 3×3 이 2열로 접혔다.
 * 반올림 방향은 폭마다 달라서 「어느 기기가 안전한가」로 막을 수 없다 — 그래서
 * **항상 기기 픽셀 하나만큼의 여유**를 남긴다. 열당 1/scale pt(3배 밀도에서 0.33pt)라
 * 눈에 보이지 않고, float32 오차(400pt 에서 ~3e-5pt)보다 네 자릿수 크다.
 *
 * 아직 재기 전(`total` 이 0)이면 `null` 이다 — 부르는 쪽이 한 프레임만 퍼센트로
 * 그리고 다음 프레임에 갈아탄다.
 */
export function columnWidth(total: number, columns: number, gap = 0): number | null {
  if (total <= 0 || columns <= 0) return null;

  const usable = total - gap * (columns - 1);
  if (usable <= 0) return null;

  const scale = PixelRatio.get();
  // 기기 픽셀로 내린 뒤 한 픽셀을 더 뺀다 — 위 「왜 한 픽셀을 더 빼나」
  const px = Math.floor((usable / columns) * scale) - 1;
  if (px <= 0) return null;

  return px / scale;
}
