/** 그 단계의 물결이 **다 퍼지기까지** — 마지막 링이 사라지는 시각이다 */
export const surfaceRippleMs = (step: SensePondStepId) => {
  const r = pondMotion.surfaceRipple;
  const it = r.step[step];
  return it.duration + it.stagger * (r.rings - 1);
};

/** 장면 안의 자리 — 폭·높이에 대한 비율(0~1) */
export type PondSpot = { x: number; y: number };

/**
 * **카피바라가 차지하는 칸** — 장면 비율(`aspect` = 높이 ÷ 폭)이 있어야 잰다.
 *
 * 그림의 세로는 폭에서 나오므로(`capybaraAspect`) 화면이 길수록 칸의 **세로 비율**은
 * 작아진다. 자리 계산(수면 터치·연잎)과 그리는 쪽이 같은 칸을 봐야 해서 여기 하나로 둔다.
 */
export const capybaraSpace = (aspect: number) => {
  const width = pondLayout.capybaraSize;
  const height = width / pondLayout.capybaraAspect / aspect;
  const bottom = 1 - pondLayout.capybaraBottom;
  return {
    left: pondLayout.capybaraLeft,
    right: pondLayout.capybaraLeft + width,
    top: bottom - height,
    bottom,
  };
};

/** 그 높이에서 물이 걸쳐 있는 좌우 끝 — 테두리 밖이면 `null` */
const waterEdges = (y: number) => {
  const rows = pondLayout.water;
  const first = rows[0]!;
  const last = rows[rows.length - 1]!;
  if (y < first.y || y > last.y) return null;
  for (let i = 0; i < rows.length - 1; i++) {
    const a = rows[i]!;
    const b = rows[i + 1]!;
    if (y >= a.y && y <= b.y) {
      const t = b.y === a.y ? 0 : (y - a.y) / (b.y - a.y);
      return { left: a.left + t * (b.left - a.left), right: a.right + t * (b.right - a.right) };
    }
  }
  return null;
};

/**
 * **여기를 건드리면 물이 반응하는가** (2026-09-06 · 보기 단계).
 *
 * 두 가지를 본다: 물의 테두리(`pondLayout.water`) 안인가, 그리고 **카피바라 칸이
 * 아닌가**. 카피바라는 손짓을 받지 않으므로(`pointerEvents="none"`) 그 위의 손짓은
 * 아래 수면으로 내려오는데, 그대로 세면 「카피바라를 눌렀더니 하나 올랐다」가 된다.
 *
 * 상단 글·뒤로가기·아래 판은 애초에 이 칸 밖이라 여기서 따로 걸러 낼 것이 없다 —
 * 물은 세로 0.5~0.77 사이에만 있다.
 */
export const isWaterSpot = (spot: PondSpot, aspect: number) => {
  const edges = waterEdges(spot.y);
  if (edges == null || spot.x < edges.left || spot.x > edges.right) return false;
  const capy = capybaraSpace(aspect);
  const onCapybara =
    spot.x >= capy.left && spot.x <= capy.right && spot.y >= capy.top && spot.y <= capy.bottom;
  return !onCapybara;
};

