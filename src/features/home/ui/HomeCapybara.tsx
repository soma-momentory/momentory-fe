import { useEffect, useState } from "react";
import { Image, Pressable, StyleSheet } from "react-native";

/**
 * 「하루 돌아보기」 카드에 앉은 **카피바라** — 가만히 앉아 있다가, 누르면
 * **손을 흔든다**(2026-09-10 · 사용자 시안).
 *
 * ## 홈에 그림이 돌아왔다
 *
 * 3세대 전환 때 홈의 날씨 씬(하늘·언덕·카피바라·병아리)을 **통째로 걷어 냈고**
 * 「일러스트·안내 그림을 두지 않는다」가 그때의 규칙이었다(`PLAN.md` A Phase 4).
 * 그 규칙은 **빈 상태를 달래려고 놓는 안내 그림**을 겨냥한 것이다 — 일정이 없는
 * 자리에 그림을 얹으면 「비어 있는 것」이 문제처럼 보인다.
 *
 * 여기 있는 카피바라는 그 자리가 아니다. **하루의 주 행동을 권하는 카드**에서
 * 말을 거는 쪽이고, 앱 안에서 이미 「함께 있는 존재」인 감각연못의 그 카피바라다
 * (`components/rest/pond/CapybaraFigure.tsx`). 빈칸을 메우지 않으므로 규칙과
 * 부딪히지 않는다 — `12-b`(일정 없음)의 초대 문구 자리는 **여전히 글자뿐이다.**
 *
 * ## 눌러도 아무 데도 가지 않는다
 *
 * 손 흔들기는 **그것으로 끝난다** — 화면도 상태도 바뀌지 않는다. 그래서
 * **낭독기에는 없는 것으로 둔다**(`accessible={false}` + 자손까지 숨김):
 * 눈으로 보는 사람에게는 반가운 반응이지만, 소리로 듣는 사람에게 「버튼」이라고
 * 읽히면 눌러 볼 곳이 하나 늘고 눌러도 얻는 것이 없다. 감각연못의 카피바라를
 * 손짓에서 빼 둔 것과 같은 판단이다(거기서는 탭이 연못으로 내려간다).
 *
 * ⚠ **카드의 CTA 를 대신하지 않는다.** 「지금 하루 돌아보기」로 가는 문은 버튼
 * 하나뿐이다 — 카피바라를 눌러도 회고가 열리지 않는다. 같은 곳으로 가는 문이 한
 * 화면에 둘이면 어느 쪽이 정식 길인지 흐려진다(`CLAUDE.md` 「코드를 쓸 때의 경계」 — 두 번째 길을 만들지 않는다).
 *
 * ## 손짓은 두 장이 전부다 — 코드가 보태는 움직임은 없다
 *
 * 가만히 있을 때는 **눈을 뜨고 팔을 내린** `idle`, 누르면 **눈을 감고 웃으며 팔을 든**
 * `wave` 로 **한 번 갈렸다가** `RAISED_MS` 뒤에 `idle` 로 돌아온다.
 *
 * ⚠ **표정까지 바뀐다**(2026-09-10 오후 · 사용자 시안). 팔만 올라가던 장을 눈웃음이
 * 있는 장으로 갈아 끼웠다 — 팔 하나보다 **얼굴이 바뀌는 편이 인사로 읽힌다.** **그림 두 장 말고는 아무것도 움직이지
 * 않는다** — 몸통 회전도, 효과선도, 크기 변화도 없다.
 *
 * ⚠ **한 번만 바뀐다**(2026-09-10 · 사용자 요청). 처음에는 네 번 갈아 끼워 팔을 두 번
 * 흔들게 했는데, 팔이 오르내리기를 되풀이하면 인사보다 **부산스럽게** 보인다.
 * 올렸다 내리는 한 번이 인사로 읽히는 최소이자 충분한 양이다.
 *
 * ⚠ **처음 받은 두 장으로는 이렇게 못 했다**(2026-09-09). 그때 그림은 팔이
 * 「휘두르는」 것이 아니라 「늘어나는」 차이라 손끝이 6.7dp 밖에 안 움직였고, 두 장만
 * 번갈아 끼우면 손짓보다 **깜빡임**에 가까웠다. 그래서 몸통을 6° 기울여 모자란
 * 「휘두름」을 만들었는데, 2026-09-10 에 **팔을 확실히 든 두 장**을 새로 받으면서
 * 기울기를 뺐다(사용자 요청). **손짓을 그림이 직접 하면 코드가 흉내 낼 것이 없다** —
 * 다음에 그림을 갈아 끼울 때도 이 기준으로 본다.
 *
 * ## 두 장을 **처음부터 둘 다 붙여 둔다**
 *
 * 누를 때 `source` 를 갈아 끼우면 **첫 손짓에서 한 번 깜빡인다**(2026-09-10 ·
 * 실기기에서 드러났다 — 「사라졌다가 뜨는 느낌」). 아직 안 그려 본 그림이라 누른
 * 순간에야 디코딩이 시작되고, 그동안 자리가 빈다.
 *
 * 그래서 **두 장을 겹쳐 놓고 `opacity` 만 바꾼다.** 붙는 순간 둘 다 디코딩되므로
 * 손짓은 이미 준비된 두 장 사이를 오가는 일이 된다. 겹쳐도 **뒤엣것이 비쳐 보이지
 * 않는다** — 안 보이는 쪽은 `opacity: 0` 이라 아예 그려지지 않는다.
 *
 * ## 움직이는 것도, 그려 넣는 것도 없다
 *
 * 든 손 옆의 **초록 손짓 줄 셋**과 발밑의 **그림자 타원**을 코드로 그렸다가 둘 다
 * 지웠다(2026-09-10 · 사용자 요청). 효과선은 가만히 있을 때도 떠 있으면 **움직이지
 * 않는 그림이 움직인다고 말하는 꼴**이라 뺐고, 그림자는 **받은 그림에 이미 그려져
 * 있어서** 뺐다 — 같은 것이 둘이면 하나는 반드시 어긋난다.
 *
 * ⚠ 그림자를 살리려고 **키아웃의 채도 문턱을 34 → 6 으로 좁혔다**
 * (`scripts/keyout-home-capybara.py`). 그림자가 무채색에 가까워서(`(219,219,206)`)
 * 넉넉한 문턱으로는 체커와 함께 지워진다. 그래서 잘라 낸 상자가 **그림자까지 품고**,
 * 그만큼 가로가 넓어져 `WIDTH` 를 함께 올렸다.
 */
/*
 * ## 그림자는 한 장이고, 바뀌는 것은 캐릭터뿐이다 (2026-09-11 · 사용자 요청)
 *
 * 받은 두 장은 그림자의 **색**(기본은 회색 · 인사는 밝은 올리브빛)도 **높이**(인사 장이 4px 아래)도
 * 달라서, 누를 때마다 그림자가 색이 튀고 내려앉았다. 게다가 인사 장은 발이 4px 더 내려가 몸이
 * 아래로 늘어나 보였다.
 *
 * 그래서 키아웃이 캐릭터 두 장에서 **그림자를 떼어 내고**, 인사 장 그림자 색으로 **한 장**을 따로
 * 만든다(`capybara-shadow.png` · 기본 장 발 밑에 맞춤). 인사 장은 **팔 아래부터 발까지만 눌러** 발을
 * 기본 장에 맞췄다(`scripts/keyout-home-capybara.py`). 화면은 그림자를 **맨 밑에 한 번만** 깔고 그 위에서
 * 캐릭터 두 장만 오간다 — 누를 때 바뀌는 것은 **눈과 든 팔**뿐이다.
 *
 * ⚠ 그림자를 캐릭터 그림에 도로 태우지 않는다 — 태우면 두 장의 그림자가 다시 따로 놀아 누를 때 튄다.
 */
type Props = {
  /** 그림의 폭 — 높이는 그림의 비율이 정한다 */
  width?: number;
};

/**
 * 홈 카드의 기본 폭 — 360dp 기기에서도 카드 제목 한 줄(142)이 남는 값이다.
 *
 * ⚠ **상자는 그림자까지 품는다.** 그림자가 몸통보다 옆으로 넓어서, 같은 상자 폭이면
 * 카피바라 자체는 그만큼 작게 그려진다 — 112 에서 118 로 올린 것이 그 보정이다
 * (몸통은 여전히 111dp 남짓이다).
 */
const WIDTH = 118;

/**
 * 가로 ÷ 세로 — 잘라 낸 그림에서 잰 값(384 × 387 · **발밑 그림자 포함**).
 * **두 장이 같은 상자에서 잘렸으므로 비율도 같다**(`scripts/keyout-home-capybara.py`).
 */
const ASPECT = 384 / 387;

/**
 * 팔을 든 채로 머무는 시간 — **누른 순간 올라가고** 이만큼 뒤에 내려온다.
 * 짧으면 깜빡인 것처럼 지나가고, 길면 인사가 아니라 굳은 자세로 보인다.
 */
const RAISED_MS = 420;

/** 두 장이 함께 쓰는 발밑 그림자 — 캐릭터 밑에 한 번만 깐다(⚠ 위 「그림자는 한 장」) */
const SHADOW = require("../../../../assets/home/capybara-shadow.png");

const FRAMES = {
  idle: require("../../../../assets/home/capybara-idle.png"),
  wave: require("../../../../assets/home/capybara-wave.png"),
};

export function HomeCapybara({ width = WIDTH }: Props) {
  const height = width / ASPECT;

  /** 지금 팔을 들고 있나 — 이 값 하나가 어느 장이 걸릴지 정한다 */
  const [raised, setRaised] = useState(false);

  useEffect(() => {
    // 흔드는 중에 또 누르면 **무시된다** — `raised` 가 이미 true 라 이 효과가 다시
    // 돌지 않는다. 손짓 하나가 끝까지 가는 편이 중간에 끊겨 되감기는 것보다 낫다
    if (!raised) return;

    // ⚠ 끝은 **타이머가 말한다** — 애니메이션이 없으므로 이것이 손짓의 전부다
    const t = setTimeout(() => setRaised(false), RAISED_MS);
    return () => clearTimeout(t);
  }, [raised]);

  return (
    <Pressable
      testID="home-capybara"
      onPress={() => setRaised(true)}
      // 낭독기에는 없는 것으로 둔다 — 눌러도 얻는 것이 없다(⚠ 위 머리말)
      accessible={false}
      importantForAccessibility="no-hide-descendants"
      accessibilityElementsHidden
      style={{ width, height }}
    >
      {/* 폭만 정하고 높이는 비율이 정한다 — 늘어난 캐릭터는 「고장 났다」로 읽힌다.
          ⚠ 둘 다 붙여 두고 `opacity` 만 바꾼다(⚠ 위 「처음부터 둘 다 붙여 둔다」) */}
      {/* 그림자는 **바뀌지 않는다** — 캐릭터만 그 위에서 오간다 */}
      <Image
        testID="home-capybara-shadow"
        source={SHADOW}
        style={[styles.frame, { width, height }]}
        resizeMode="contain"
      />
      <Image
        testID="home-capybara-idle"
        source={FRAMES.idle}
        style={[styles.frame, { width, height, opacity: raised ? 0 : 1 }]}
        resizeMode="contain"
      />
      <Image
        testID="home-capybara-wave"
        source={FRAMES.wave}
        style={[styles.frame, { width, height, opacity: raised ? 1 : 0 }]}
        resizeMode="contain"
      />
    </Pressable>
  );
}

const styles = StyleSheet.create({
  // 두 장이 같은 자리에 겹쳐 선다 — 상자 크기는 `Pressable` 이 들고 있다
  frame: { position: "absolute", left: 0, top: 0 },
});
