/**
 * 감각연못 — 쉼 콘텐츠 첫 번째
 * (2026-09-03 · 손짓 구조 개편 2026-09-05 · 수면 터치 2026-09-06 ·
 * 표시·결과물 걷어내기 2026-09-06).
 *
 * 현실에서 감각 하나를 찾을 때마다 **연못 안의 감각 포인트를 하나씩 눌러** 앞으로
 * 가는 콘텐츠다. 연못은 이미 완성된 풍경이고, 사용자가 하는 일은 **거기 있는 것을
 * 발견하는 것**이다 — 연못을 눌러 무언가를 만들어 놓는 것이 아니다(2026-09-05 개편).
 *
 * ## 만들지 않고 발견한다
 *
 * 옛 구조는 연못 아무 데나 톡 건드리면 그 자리에 연잎·소리 자국·꽃이 **새로 생겼다**.
 * 그러면 화면이 「내가 물건을 놓는 곳」이 되고, 연못 그림 속 연잎과 내가 놓은 연잎이
 * 서로 다른 층으로 읽혀 풍경이 둘로 갈렸다. 지금은 반대다 — 그림 속 연잎·돌·꽃은
 * **처음부터 있는 풍경**이고, 우리는 그 위에 **감각 포인트**(눈·소리·손)만 얹는다.
 * 누르면 그 자리에서 작은 물결 하나가 퍼지고 포인트는 조용히 사라진다. 연못에
 * 남는 것은 없다 — 남는 것은 사용자가 방금 찾은 **실제 감각**이다.
 *
 * ## 미니게임이 아니라 쉼터다 (2026-09-06)
 *
 * 한때는 연못 위에 눈·음표·손 **표시**가 떠 있고 그것을 찾아 누르는 단계였다.
 * 그러면 사용자가 보는 것은 **현실**이 아니라 화면 속 아이콘이 된다 — 「주변을
 * 둘러보세요」라고 말해 놓고 눈은 화면에서 숨은그림찾기를 한다. 손짓마다 연잎이
 * 하나씩 떠오르던 것도 지웠다: 무언가를 모으는 화면이 되면 쉼이 수집이 된다.
 *
 * 지금은 **셋 다 같은 방식**이다. 현실에서 감각 하나를 찾고 **연못의 물 아무
 * 데나** 건드리면, 그 자리에서 물결이 조용히 퍼지고 셈이 하나 오른다. 연못에
 * 남는 것은 없다 — 남는 것은 사용자가 방금 찾은 **실제 감각**이다.
 * (감각 단계만 톡이 아니라 **잠시 누르고 있기**다 — 몸에 닿는 감각은 한 번에
 * 알아채는 것이 아니라 머물러야 느껴진다.)
 *
 * ## 상단은 한 번에 한 가지만 말한다 (2026-09-06)
 *
 * 옛 화면은 제목(`SENSE_POND_TITLE`) · 한 줄(`SENSE_POND_SUBTITLE`) · 단계 제목 ·
 * 단계 설명 · 보조 문구를 **한꺼번에** 위에 쌓았다. 다섯 줄이 동시에 말을 걸면
 * 어느 것이 「지금 할 일」인지 고르는 일부터 해야 해서, 정작 눈을 둘 곳(연못)에
 * 시선이 가지 않았다. 그래서 문안을 **셋으로 갈랐고**, 화면은 한 번에 하나만 쓴다:
 *
 * | 언제              | 무엇                                                        |
 * | ----------------- | ----------------------------------------------------------- |
 * | 들어온 직후(소개) | `SENSE_POND_TITLE` + `SENSE_POND_SUBTITLE`                  |
 * | 진행 중           | 그 단계의 `title` + `description` (제목 한 줄 · 설명 한두 줄) |
 * | 완료              | `SENSE_POND_DONE` 의 `title` + `description`                |
 *
 * 소개는 **들어온 순간에만** 있다 — `pondMotion.introHold` 가 지나거나 첫 포인트를
 * 찾으면 물러나고, 그 뒤로 다시 오지 않는다. 진행 중에 브랜드 이름과 태도 문구가
 * 남아 있으면 「지금 할 일」이 셋째 줄로 밀린다. 완료에는 단계 설명이 하나도 없다.
 *
 * ## 문안은 여기 산다
 *
 * 단계 제목 · 설명 · 셈 라벨은 제품 문안이라 화면이 아니라 도메인에 둔다
 * (`contents.ts` 와 같은 판단). 화면은 `SENSE_POND_STEPS` 를 순서대로 밟고,
 * 단계가 늘면 이 표에만 더한다 — **크기·시간·자리는 디자인이라 여기 없다**
 * (`ds/pond.ts`).
 *
 * ## 세는 것은 「찾은 개수」뿐이다
 *
 * 「숫자로 압박하지 않는다」(`RULES.md` 4)는 진행률·연속 일수 얘기다. 여기 `0 / 3`
 * 은 **이 콘텐츠의 놀이 규칙**이라 남긴다 — 다만 목표를 넘겨 세지 않고(목표에서
 * 멈춘다) 시간을 재지 않는다.
 */
export type SensePondStepId = "see" | "hear" | "feel";

/** 연못에 뜨는 감각 포인트의 종류 — 보기는 눈, 듣기는 소리, 감각은 손 */
export type SensePointKind = "eye" | "sound" | "hand";

/**
 * 그 단계에 건네는 손짓 — **어느 쪽이든 받는 것은 수면 하나**다 (2026-09-06).
 *
 * - `tap` — 물을 톡 건드린다 (보기 · 듣기)
 * - `hold` — 물에 손을 얹고 잠시 있는다 (감각 · `pondMotion.hold`)
 */
export type PondInput = "tap" | "hold";

export type SensePondStep = {
  id: SensePondStepId;
  /** 단계 제목 — 「보이는 것 3개」 */
  title: string;
  /**
   * 지금 할 행동 **한 줄(길어도 두 줄)** — `contents.ts` 와 같은 이유로 도메인에 둔다.
   * 쉼터 홈이 이미 콘텐츠를 설명했으므로 여기서 감각연못 자체를 다시 설명하지 않는다.
   *
   * ⚠ **예시를 덧붙여 세 줄로 만들지 않는다**(2026-09-06). 진행 중 상단은 제목 한 줄과
   * 이 한두 줄이 전부여야 시선이 장면으로 간다 — 그래서 옛 `note`(설명 아래 보조 문구
   * 한 줄)는 사라졌고, 필요한 예시는 이 문장 안에 짧게 붙인다(`feel`).
   */
  description: string;
  /** 찾아야 하는 개수. 셈은 여기서 멈춘다 — 목표를 넘겨 세지 않는다 */
  goal: number;
  /** 셈 앞의 라벨 — 「보이는 것 0 / 3」 */
  counterLabel: string;
  /** 아래 패널의 한 칸 이름 — 셋이 나란히 서므로 짧다(「몸에 닿는 감각」이 아니라 「닿는 감각」) */
  panelLabel: string;
  /** 이 감각의 표 — **아래 판의 한 칸**이 이 글리프를 든다(연못 위에는 없다) */
  point: SensePointKind;
  /** 이 단계의 손짓 */
  input: PondInput;
};

