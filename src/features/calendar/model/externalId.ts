import { cyrb128 } from "@/features/calendar/model/hash";

/**
 * 회차 하나를 가리키는 키 — **서버가 upsert 에 쓰는 값이다.**
 *
 * 세 가지를 섞는다. 셋 다 이유가 있다:
 *
 * | 입력         | 없으면                                                             |
 * | ------------ | ------------------------------------------------------------------ |
 * | `calendarId` | 계정이 둘인데 이벤트 id 가 겹치면 **서로 다른 일정이 한 줄로 합쳐진다** |
 * | `eventId`    | 반복 회차라면 플랫폼 차이를 걷어낸 원본 시리즈 id다                 |
 * | `date`       | **반복 일정의 회차들이 `eventId` 를 공유한다**(실측) — 날짜가 없으면 매주 회의가 한 줄이 된다 |
 *
 * ## `instanceId` 를 쓰지 않는다
 *
 * Android 전용인 데다 expo 가 스스로 "volatile ID … 항상 같은 인스턴스를 가리킨다고
 * 보장하지 않는다"고 적어 뒀다. 앱을 열 때마다 값이 달라지면 화해가 **매번 지웠다
 * 새로 만든다** — 그 일정에 달린 감정·마침 기록이 함께 날아간다.
 *
 * ## 이것이 영구 식별자라고 가정하지 않는다
 *
 * Android 의 이벤트 id 는 **로컬 DB 행 번호**다. 계정을 지웠다 다시 붙이거나
 * 캘린더 앱 데이터를 초기화하면 새로 매겨진다. 반복 일정의 한 회차만 고쳐도
 * 새 id 를 받을 수 있다.
 *
 * **그래도 데이터가 꼬이지 않는 이유는 키가 완벽해서가 아니라 범위 화해가
 * 정본이기 때문이다** — 옛 키는 목록에서 사라져 삭제되고 새 키는 생성된다.
 * 여기서 노리는 것은 「흔한 경우에 키가 흔들리지 않게」까지다.
 *
 * ## 왜 해시로 감싸나
 *
 * 서버는 이 값을 **불투명 문자열**로 다룬다 — `@` 든 `:` 든 파싱하지 않는다.
 * 그래야 나중에 입력을 하나 더 섞어도 서버가 바뀌지 않는다. 그리고 원문을 그대로
 * 보내면 **달력 id 와 계정 구조가 서버 로그에 남는다**(§5 「달력 이름·계정은 안 보낸다」).
 */
export const makeExternalId = (input: {
  calendarId: string;
  eventId: string;
  /** `YYYY-MM-DD` · 04:00 경계로 접은 그 회차의 날짜 */
  date: string;
}): string =>
  // 길이를 앞에 붙여 잇는다 — 구분자만으로는 "1"+"23" 과 "12"+"3" 이 갈리지 않는다
  cyrb128(
    `${input.calendarId.length}:${input.calendarId}` +
      `${input.eventId.length}:${input.eventId}` +
      `${input.date.length}:${input.date}`,
  );
